#!/usr/bin/env python3
"""Write a .env with random secrets, from .env.example.

    python3 scripts/generate_env.py > .env                     # development
    python3 scripts/generate_env.py --production \\
        --domain data.example.com --email ops@example.com > .env

Every password and key the stack needs is generated (32 random bytes,
URL-safe). Provider API keys are left empty: add yours. With --production,
the file also selects docker-compose.prod.yml and holds the domain, the
Let's Encrypt contact and the API's basic-auth account. The API password is
printed once, to stderr; only its bcrypt hash is written (made with the proxy
image's `caddy hash-password`, so Docker is needed).

Then: chmod 600 .env, and check it with scripts/check_env.py.
Standard library only.
"""

import argparse
import secrets
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from env_file import parse, quote  # noqa: E402

REPOSITORY = Path(__file__).resolve().parents[1]
EXAMPLE = REPOSITORY / ".env.example"
CADDY_IMAGE = "caddy:2.11.9-alpine"

GENERATED = (
    "POSTGRES_PASSWORD",
    "BACKEND_DB_PASSWORD",
    "GRAFANA_ADMIN_PASSWORD",
    "GRAFANA_DB_PASSWORD",
    "ADMIN_API_KEY",
)


def secret() -> str:
    return secrets.token_urlsafe(32)


def bcrypt(password: str) -> str:
    result = subprocess.run(
        ["docker", "run", "--rm", "-i", CADDY_IMAGE, "caddy", "hash-password"],
        input=password + "\n" + password + "\n",
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip().splitlines()[-1]


def generate(production: bool, domain: str | None, email: str | None) -> str:
    template = EXAMPLE.read_text()
    values = {key: secret() for key in GENERATED}
    if production:
        api_password = secret()
        values |= {
            "COMPOSE_FILE": "docker-compose.yml:docker-compose.prod.yml",
            "DOMAIN": domain or "",
            "ACME_EMAIL": email or "",
            "API_USERNAME": "api",
            "API_PASSWORD_HASH": bcrypt(api_password),
        }
        print(f"API basic-auth account: api / {api_password}", file=sys.stderr)
        print("Store the password now; only its hash is in the file.", file=sys.stderr)

    lines = []
    for line in template.splitlines():
        stripped = line.lstrip("# ")
        key = stripped.split("=", 1)[0] if "=" in stripped else None
        if key in values and (not line.startswith("#") or production):
            lines.append(f"{key}={quote(values.pop(key))}")
        else:
            lines.append(line)
    if values:
        lines += ["", *(f"{key}={quote(value)}" for key, value in values.items())]
    header = "# Generated by scripts/generate_env.py. Never commit this file; chmod 600 it.\n"
    return header + "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--production", action="store_true")
    parser.add_argument("--domain", help="the public host name, for example data.example.com")
    parser.add_argument("--email", help="contact address for Let's Encrypt")
    args = parser.parse_args()
    if args.production and not (args.domain and args.email):
        parser.error("--production needs --domain and --email")
    output = generate(args.production, args.domain, args.email)
    # Sanity: the result parses and has every generated secret.
    parsed = parse(output)
    assert all(parsed.get(key) for key in GENERATED)
    sys.stdout.write(output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
